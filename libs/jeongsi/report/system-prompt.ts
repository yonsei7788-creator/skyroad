/**
 * 플랜/학생별 시스템 프롬프트의 가변 부분.
 *
 * JEONGSI_COMMON_SYSTEM_PROMPT 는 Gemini 컨텍스트 캐시에 담겨 재사용되므로,
 * 학생마다 달라지는 지원 조건은 이 prefix 로 분리해 주입한다.
 */
export const buildJeongsiSystemPrefix = (
  preference: JeongsiPreference
): string => {
  const targetLabel = TARGET_KIND_LABEL[preference.targetKind];

  return `## 이 학생의 지원 조건

- 희망 ${targetLabel}: ${preference.target}
- 희망 지역: ${preference.region}
- 지원 성향: ${preference.risk}

### 지원 조건을 해설에 반영하는 방법

- 추천 대학·학과 목록은 위 조건을 이미 반영해 코드가 선정한 결과입니다. 목록에 담긴 대학과 학과를 전제로 해설합니다.
- ${RISK_GUIDE[preference.risk]}
- 희망 지역은 목록 선정에 반영되어 있으므로, 지역을 다시 판단하기보다 목록에 있는 대학의 반영방식과 격차를 설명하는 데 집중합니다.`;
};
